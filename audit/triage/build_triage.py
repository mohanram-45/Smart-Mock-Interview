import pandas as pd, json, re, collections
from load_all import D
pj=pd.read_pickle('/home/claude/work/audit_clean/processed_annotated.pkl')
ct=json.load(open('code_test_results.json'))
PFX=re.compile(r'^(Ans\.\s*|Solution:\s*)')
def strip_prefix(s): return PFX.sub('',s).strip()
rows=[]
for _,r in pj.iterrows():
    i=int(r['id']); base=dict(id=i,raw_id=r.raw_id,
        source_file=('expanded_interview_questions.csv' if r.src=='generated' else 'questions_seed.csv'),
        source_type=r.src, raw_domain=r.raw_domain, domain=r.domain,
        raw_difficulty=r.raw_difficulty, difficulty=r.difficulty,
        question=r.question, reference_answer=r.reference_answer)
    if r.src=='generated':
        base.update(status='EXCLUDE_TEMPLATE',review_state='n/a',flags='TEMPLATE_GENERATED',
            note='generated by scripts/expand_interview_dataset.py (12 question templates x topic); answer is a description of a good answer, not a reference answer; difficulty set by keyword rebalance')
        rows.append(base); continue
    d=D[i]
    pa=d.get('pa'); basis=''
    if pa: basis='rewritten_answer'
    elif d.get('trim') or d.get('repl') or ('COSMETIC_PREFIX' in d['flags'] and d['status']=='FIX'):
        a=r.reference_answer
        if d.get('trim'): a=a[:a.index(d['trim'])]; basis='trim'
        for o,n in (d.get('repl') or []):
            a=a.replace(o,n); basis=(basis+'+' if basis else '')+'replace'
        pa=strip_prefix(a)
        if pa: pa=pa[0].upper()+pa[1:]
        if basis=='' : basis='prefix_strip'
    pq=d.get('pq')
    if pq and not pa and d['status']=='FIX' and d.get('repl'):
        pass
    # question-side repl (e.g. typos in question)
    if d['status']=='FIX' and d.get('repl') and not pq:
        q=r.question
        for o,n in d['repl']:
            q=q.replace(o,n)
        if q!=r.question: pq=q
    cr=ct.get(str(i)) or ct.get(i)
    code_status='NA'
    if d.get('code'):
        code_status='PASS' if cr and cr['rc']==0 else 'FAIL_OR_NOT_RUNNABLE'
    elif 'REQUIRES_CODE' in d['flags']: code_status='NOT_TESTED'
    st=d.get('state') if d['status']=='FIX' else 'n/a'
    if st=='needs_code_test' and code_status=='PASS': st='ready_for_approval'
    base.update(status=d['status'],review_state=st,
        flags=';'.join(d['flags']),
        proposed_domain=d.get('pd') or '', proposed_difficulty=d['pdiff'],
        proposed_question=pq or '', proposed_answer=pa or '', proposal_basis=basis,
        proposal_confidence=d.get('conf') or '', duplicate_of=d.get('dup_of') or '',
        code_test=code_status, note=d['note'])
    rows.append(base)
cols=['id','raw_id','source_file','source_type','status','review_state','domain','raw_domain','proposed_domain','difficulty','raw_difficulty','proposed_difficulty','flags','proposal_confidence','proposal_basis','duplicate_of','code_test','note','question','reference_answer','proposed_question','proposed_answer']
df=pd.DataFrame(rows)
for c in cols:
    if c not in df: df[c]=''
df=df[cols].fillna('')
df['duplicate_of']=df['duplicate_of'].apply(lambda x: int(x) if x!='' else '')
df.to_csv('/home/claude/work/out/data/audit/triage.csv',index=False,encoding='utf-8')
print(df.status.value_counts().to_dict(), len(df))
df.to_pickle('triage_df.pkl')
